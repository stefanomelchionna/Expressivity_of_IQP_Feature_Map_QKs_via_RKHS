def make_all_plots(out_dir=OUTPUT_DIR):
    """Generate every figure and write it to `out_dir` (png and pdf), overwriting previous files."""
    apply_style()
    dfs, scan = load_results()
    print(f"Writing figures to {out_dir}")

    def make(stem, build):
        with text_scale(FIGURE_TEXT_SCALE.get(stem, 1.0)):
            save_fig(build(), stem, out_dir)

    for cfg in HEATMAPS.values():
        make(cfg["stem"], lambda cfg=cfg: heatmap_figure(dfs[cfg["df_key"]], cfg))

    for cfg in TRENDS_PERIODIC.values():
        make(cfg["stem"], lambda cfg=cfg: plot_periodic(dfs[cfg["task"]], scan, cfg))
    for cfg in TRENDS_MULTIMODAL.values():
        make(cfg["stem"], lambda cfg=cfg: plot_multimodal(dfs[cfg["task"]], scan, cfg))
    make("Trend_multimodal_gammaband", lambda: plot_multimodal_combined(dfs, scan))

    for key, stem in COMBINED_PERIODIC_STEMS.items():
        make(stem, lambda key=key: combined_periodic_figure(dfs, scan, key))

    make(RKHS_FOURIER["stem"], lambda: rkhs_fourier_figure(RKHS_FOURIER))
    make(RKHS_QUANTUM["stem"], lambda: rkhs_quantum_figure(RKHS_QUANTUM))
    make(RKHS_RBF["stem"], lambda: rkhs_rbf_figure(RKHS_RBF))

    make(DS_STEM, datasets_figure)

    for cfg in SUPPLEMENTARY.values():
        make(cfg["stem"], lambda cfg=cfg: supplementary_figure(dfs[cfg["task"]], cfg))


if __name__ == "__main__":
    make_all_plots()
