def quantum_periodic(df, metric):
    """Quantum curve on the diagonal bandwidth = oscillations, aggregated over reps and entanglement."""
    q = df[(df.K_type == "Quantum") & (df.Sampling == SAMPLING)]
    q = q[q.oscillations == q.Bandwidth]
    return (q.groupby(["N_qubits", "oscillations"])[metric]
            .agg(mean="mean", low="min", high="max").reset_index())


def quantum_multimodal(df, metric):
    """Quantum curve for multimodal data: metric as a function of the bandwidth."""
    q = df[(df.K_type == "Quantum") & (df.Sampling == SAMPLING)]
    return (q.groupby(["N_qubits", "N_clusters", "Bandwidth"])[metric]
            .agg(mean="mean", low="min", high="max").reset_index())


def band_table(scan, task):
    """Min-max of the RBF metric over the gamma scan and value at the default gamma, per configuration."""
    sub = scan[scan.Task == task]
    keys = ["N_qubits", "structure"]
    agg = (sub[~sub.is_default].groupby(keys)["metric"]
           .agg(band_low="min", band_high="max").reset_index())
    dflt = sub[sub.is_default][keys + ["metric"]].rename(columns={"metric": "default_metric"})
    return agg.merge(dflt, on=keys)


# ---------------------------------------------- periodic heatmaps -----------------------------------------------

def panel_subsets(df, best):
    """Rows of the panels: (a) quantum configuration `best`, (b) all quantum configurations,
    (c) classical RBF (bandwidth = 1, i.e. not applied)."""
    base = df[df["Sampling"] == SAMPLING]
    q = base[base["K_type"] == "Quantum"]
    mask = np.ones(len(q), dtype=bool)
    for col, val in best.items():
        mask &= (q[col] == val).to_numpy()
    c = base[(base["K_type"] == "Classical") & (base["Bandwidth"] == 1)]
    return q[mask], q, c


def to_pivot(sub, metric):
    return sub.groupby(["oscillations", "Bandwidth"])[metric].mean().unstack("Bandwidth")


def plot_heatmap(ax, pivot, panel, vmin, vmax, show_ylabels=False, highlight_diagonal=False):
    im = ax.imshow(pivot.values, aspect="auto", cmap=HEATMAP_CMAP, vmin=vmin, vmax=vmax)

    ax.set_xticks(range(pivot.shape[1]))
    ax.set_xticklabels([f"{c:g}" for c in pivot.columns])
    ax.set_yticks(range(pivot.shape[0]))
    if show_ylabels:
        ax.set_yticklabels([f"{r:g}" for r in pivot.index])
        ax.set_ylabel("Oscillations")
    else:
        ax.set_yticklabels([])
    ax.set_xlabel("Bandwidth")
    ax.tick_params(length=0)

    # border between cells
    ax.set_xticks(np.arange(-0.5, pivot.shape[1]), minor=True)
    ax.set_yticks(np.arange(-0.5, pivot.shape[0]), minor=True)
    ax.grid(which="minor", color=HM_GRID_COLOR, linewidth=HM_GRID_WIDTH)
    ax.tick_params(which="minor", length=0)
    for s in ax.spines.values():
        s.set_visible(False)

    # cell values, text colour depending on the cell luminance
    for i in range(pivot.shape[0]):
        for j in range(pivot.shape[1]):
            val = pivot.iloc[i, j]
            if np.isnan(val):
                continue
            r, g, b, _ = im.cmap(im.norm(val))
            lum = 0.299 * r + 0.587 * g + 0.114 * b
            ax.text(j, i, f"{val:.{ANNOT_DECIMALS}f}", ha="center", va="center", fontsize=fs(ANNOT_SIZE),
                    color="black" if lum > ANNOT_LUM_THRESHOLD else "white")

    if highlight_diagonal:
        for i, osc in enumerate(pivot.index):
            for j, bw in enumerate(pivot.columns):
                if np.isclose(osc, bw):
                    ax.add_patch(Rectangle((j - 0.5, i - 0.5), 1, 1, fill=False, edgecolor=DIAG_COLOR,
                                           linewidth=2.0, zorder=5, clip_on=False))

    panel_label(ax, panel)
    return im


def heatmap_width_ratios(include_classical):
    return [1, 1, 1, 1] + ([HM_C_WIDTH] if include_classical else []) + [HM_CBAR_WIDTH]


def draw_heatmaps(fig, spec, df, metric, best, cbar_label, vmin=None, vmax=None, include_classical=False):
    """Heatmap panels in the region `spec` of the figure:
    (a) quantum, configuration `best` | (b) quantum, mean | (c) classical RBF (if include_classical)."""
    sub_best, sub_q, sub_c = panel_subsets(df, best)
    subsets = (sub_best, sub_q, sub_c) if include_classical else (sub_best, sub_q)
    pivots = [to_pivot(s, metric) for s in subsets]

    if vmin is None or vmax is None:
        vals = np.concatenate([p.values.ravel() for p in pivots])
        vmin = np.nanmin(vals) if vmin is None else vmin
        vmax = np.nanmax(vals) if vmax is None else vmax

    width_ratios = heatmap_width_ratios(include_classical)
    gs = spec.subgridspec(1, len(width_ratios), width_ratios=width_ratios, wspace=HM_WSPACE)
    axes = [fig.add_subplot(gs[0, 0:2]), fig.add_subplot(gs[0, 2:4])]
    if include_classical:
        axes.append(fig.add_subplot(gs[0, 4]))
    cax = fig.add_subplot(gs[0, -1])

    for i, (ax, pivot) in enumerate(zip(axes, pivots)):
        im = plot_heatmap(ax, pivot, f"({'abc'[i]})", vmin, vmax, show_ylabels=(i == 0),
                          highlight_diagonal=(i == 0 and HIGHLIGHT_DIAGONAL))
    style_colorbar(fig.colorbar(im, cax=cax), cbar_label)
    return axes


def heatmap_figure(df, cfg):
    unit = HM_MAIN_PANEL_WIDTH / 2
    fig = plt.figure(figsize=(unit * sum(heatmap_width_ratios(cfg["include_classical"])), HM_FIG_HEIGHT))
    draw_heatmaps(fig, fig.add_gridspec(1, 1)[0, 0], df, cfg["metric"], cfg["best"], cfg["cbar_label"],
                  cfg["vmin"], cfg["vmax"], cfg["include_classical"])
    return fig


