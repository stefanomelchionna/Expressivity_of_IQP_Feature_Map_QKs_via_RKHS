def zz_states(points, reps):
    """Statevector of the 2-qubit ZZFeatureMap (linear entanglement) for every row of `points`.
    Each repetition: H on both qubits, then the diagonal part P(2 x_0), P(2 x_1), CX P(2 (pi-x_0)(pi-x_1)) CX.
    Qiskit little-endian order: index = b0 + 2 * b1. Matches FidelityQuantumKernel to 1e-14."""
    x0, x1 = points[:, 0], points[:, 1]
    b0 = np.array([0, 1, 0, 1])
    b1 = np.array([0, 0, 1, 1])
    phase = np.exp(1j * (2 * np.outer(x0, b0) + 2 * np.outer(x1, b1)
                         + 2 * np.outer((np.pi - x0) * (np.pi - x1), b0 ^ b1)))
    h = np.array([[1, 1], [1, -1]]) / np.sqrt(2)
    hh = np.kron(h, h)
    psi = np.zeros((len(points), 4), dtype=complex)
    psi[:, 0] = 1
    for _ in range(reps):
        psi = phase * (psi @ hh.T)
    return psi


def rkhs_function(bandwidth, reps, n_points):
    """f(x) = k(x_0, x) on the grid [0, b]^2 with x_0 at the centre."""
    x = np.linspace(0, bandwidth, n_points)
    X, Y = np.meshgrid(x, x)
    grid = np.column_stack([X.ravel(), Y.ravel()])
    centre = np.array([[bandwidth / 2, bandwidth / 2]])
    k = np.abs(zz_states(grid, reps) @ zz_states(centre, reps).conj().T)[:, 0] ** 2
    return k.reshape(n_points, n_points)


def rbf_function(gamma, n_points):
    """f(x) = exp(-gamma ||x - x_0||^2) on the grid [0, 1]^2 with x_0 at the centre."""
    x = np.linspace(0, 1, n_points)
    X, Y = np.meshgrid(x, x)
    return np.exp(-gamma * ((X - 0.5) ** 2 + (Y - 0.5) ** 2))


def fourier_magnitude(F):
    """Modulus of the centred 2D FFT of the zero-mean function, normalised by the number of points."""
    F = F - F.mean()
    return np.abs(np.fft.fftshift(np.fft.fft2(F))) / F.size


def bandwidth_label(bw):
    frac = {1 / 8: "\\pi/8", 1 / 4: "\\pi/4", 1 / 2: "\\pi/2", 1: "\\pi"}
    r = bw / np.pi
    for v, s in frac.items():
        if np.isclose(r, v):
            return f"${s}$"
    return f"${r:g}\\pi$"


