'''
Generate all the figures of the paper in one go, from the result CSVs in output/.

Figure of the paper              -> output file (images/report_plots/<stem>.png and .pdf)
  Fig. 1  Gaussian RKHS generators   RKHS_RBF
  Fig. 6  quantum RKHS generators    RKHS_quantum
  Fig. 7  Fourier transform of RKHS  RKHS_fourier_transform_heatmaps
  Fig. 8  datasets                   datasets
  Fig. 9  periodic classification    combined_periodic_classification
  Fig. 10 periodic anomaly detection combined_periodic_AD
  Fig. 11 multimodal data            Trend_multimodal_gammaband
  Fig. S1-S4 per repetition/entanglement   supplementary_S1 ... supplementary_S4
  (Figs. 2-5 are circuit diagrams, not generated by code.)
The single panels of Figs. 9-11 are also written as separate files (heatmap_*, Mean_interaction_*, *_gammaband).

Inputs:
  output/<Experiment>/*.csv                           quantum (and classical default-gamma) results, written by
                                                      experiments/evaluation/*.py
  output/RBF_gamma_scan/gamma_decades_scan_f1_ts.csv  classical RBF over gamma in {0.01, 0.1, 1, 10, 100} + default,
                                                      written by gamma_study/compute_gamma_decades.py --clf-metric f1_ts

The script is organised in three parts:
1. CONFIGURATION: every setting (paths, fonts, text sizes, colours, the configurations shown in the
   periodic heatmaps, the parameters of the RKHS and dataset figures, layout). Text sizes are shared by all
   figures: changing e.g. AXIS_LABEL_SIZE changes the axis labels of every plot.
2. FUNCTIONS: data loading and the functions drawing each figure.
3. WRAP-UP: make_all_plots() builds every figure and writes it as png and pdf to images/report_plots/,
   overwriting the files of a previous run.

Run from anywhere:  python code_for_papers_plots/make_report_plots.py
Requires numpy, pandas, matplotlib, seaborn, scikit-learn (for the dataset figure, through src/data.py).
'''

