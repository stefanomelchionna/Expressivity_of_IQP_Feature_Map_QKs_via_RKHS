def periodic_boundary(ax, oscillations):
    """Boundary sin(2 pi w x^1) + sin(2 pi w x^2) = 0 in the unit square.
    From sin a + sin b = 2 sin((a+b)/2) cos((a-b)/2) it is the union of the lines
    x^1 + x^2 = k / w  and  x^1 - x^2 = (2k + 1) / (2 w)."""
    w = oscillations
    t = np.array([0.0, 1.0])
    kw = dict(color=DS_BOUNDARY_COLOR, lw=DS_BOUNDARY_WIDTH, zorder=3, solid_capstyle="butt")
    for k in range(1, 2 * w):                 # x^2 = k/w - x^1
        ax.plot(t, k / w - t, **kw)
    for k in range(-w, w):                    # x^2 = x^1 - (2k+1)/(2w)
        ax.plot(t, t - (2 * k + 1) / (2 * w), **kw)


